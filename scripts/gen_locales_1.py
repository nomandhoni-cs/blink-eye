# -*- coding: utf-8 -*-
"""Generate locale catalogs by merging per-locale overlays onto en.json."""
import copy
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LOCALES = os.path.join(ROOT, "src", "i18n", "locales")
EN = json.load(open(os.path.join(LOCALES, "en.json"), encoding="utf-8"))


def merge(base, overlay):
    out = copy.deepcopy(base)
    for k, v in overlay.items():
        if isinstance(v, dict) and isinstance(out.get(k), dict):
            out[k] = merge(out[k], v)
        else:
            out[k] = copy.deepcopy(v)
    return out


def write(code, overlay):
    merged = merge(EN, overlay)
    path = os.path.join(LOCALES, f"{code}.json")
    with open(path, "w", encoding="utf-8") as f:
        json.dump(merged, f, indent=2, ensure_ascii=False)
        f.write("\n")
    print("wrote", code)


